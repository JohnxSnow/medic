def triage_patient_symptom(user_query: str) -> Dict[str, Any]:
    """
    Evaluates patient complaint using precise evidence-based clinical rules.
    STRICT MEDICAL RULE: ZERO HALLUCINATION. NEVER PRESCRIBES DRUGS.
    Returns structured medical guidance with non-pharmacological care and doctor specialist.
    """
    if not user_query or len(user_query.strip()) < 3:
        return {
            "success": False,
            "error_kurdish": "تکایە بە کورتی نیشانەکانت یان شوێنی ئازارەکەت بنووسە (بۆ نموونە: سنگم دێشێت، سکی لای ڕاستم ئازاری هەیە، سەرم دەتەقێت، چاوم سوور بووە، ددانم دەکوڵێت)..."
        }

    raw_q = user_query.lower()
    norm_q = normalize_kurdish(raw_q)

    best_match = None
    highest_score = 0

    for rule in CLINICAL_TRIAGE_RULES:
        score = 0
        anatomy_matched = False
        trigger_matched = False

        # 1. Match Anatomy / Anatomical Root
        anat_matches = 0
        for anat in rule["anatomy_tokens"]:
            if token_matches_text(anat, norm_q, raw_q):
                anat_matches += 1

        if anat_matches > 0:
            anatomy_matched = True
            score += 35 + (anat_matches - 1) * 15

        # 2. Match Trigger / Qualifier
        trig_matches = 0
        for trig in rule["trigger_tokens"]:
            if token_matches_text(trig, norm_q, raw_q):
                trig_matches += 1

        if trig_matches > 0:
            trigger_matched = True
            score += 25 + (trig_matches - 1) * 15

        # CRITICAL SAFETY: An emergency condition MUST have an explicit emergency trigger keyword matched!
        # A simple body part complaint like "سەرم دێشێت" or "sarm esh akat" is NOT a subarachnoid hemorrhage or heart attack.
        if rule.get("severity") == "emergency" and not trigger_matched:
            continue

        # Boost if both anatomy and trigger matched
        if anatomy_matched and trigger_matched:
            score += 40

        # High priority for emergencies only if both anatomy and trigger matched
        if rule.get("severity") == "emergency" and anatomy_matched and trigger_matched:
            score += 10

