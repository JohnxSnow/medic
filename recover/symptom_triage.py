def normalize_kurdish(text: str) -> str:
    if not text:
        return ""
    t = text.lower().strip()
    
    # Common Latin-to-Kurdish transliteration mappings for Kurdish phonetic typing
    latin_to_kurdish = {
        "esh akat": "دێشێت", "esh dakat": "دێشێت", "deshe": "دێشێت", "deshet": "دێشێت",
        "sarm": "سەرم", "sar": "سەر",
        "skm": "سکم", "sk": "سک",
        "singm": "سنگم", "sing": "سنگ",
        "dilm": "دڵم", "dil": "دڵ",
        "kamarm": "کەمەرم", "kamar": "کەمەر",
        "pshtm": "پشتم", "psht": "پشت",
        "ddanm": "ددانم", "ddan": "ددان", "pukm": "پووکم", "puk": "پووک",
        "chawm": "چاوم", "chaw": "چاو",
        "gwem": "گوێم", "gwe": "گوێ", "gwezringan": "گوێزرینگان",
        "qwrgm": "قوڕگم", "qwrg": "قوڕگ",
        "zrawm": "زراوم", "zraw": "زراو",
        "gurchilam": "گورچیلەم", "gurchila": "گورچیلە",
        "mndalakam": "منداڵەکەم", "mndal": "منداڵ",
        "pestanm": "پەستانم", "pestan": "پەستان",
        "shakram": "شەکرەم", "shakra": "شەکرە"
    }
    for l_key, k_val in latin_to_kurdish.items():
        if l_key in t:
            t = t.replace(l_key, k_val)

    replacements = {
        'ك': 'ک', 'ي': 'ی', 'ى': 'ی', 'ێ': 'ی',
        'ف': 'ڤ', 'ة': 'ە', 'ه': 'ە', 'ۆ': 'و',
        'ڵ': 'ل', 'ڕ': 'ر', 'أ': 'ا', 'إ': 'ا', 'آ': 'ا',
        'ـ': '', '؟': '', '?': '', '!': '', '.': '', ',': '', '،': '',
        'ئێ': 'ی', 'ئو': 'و', 'ئی': 'ی'
    }
    for k, v in replacements.items():
        t = t.replace(k, v)
    return t

def token_matches_text(token: str, norm_text: str, raw_text: str) -> bool:
    norm_token = normalize_kurdish(token)
    if not norm_token:
        return False
    
    # Direct phrase match for multi-word expressions
    if " " in norm_token:
        return norm_token in norm_text or token in raw_text

    # Word-level checking to avoid subword collisions (e.g. پێ inside پێست)
    words = norm_text.split()
    for w in words:
        if w == norm_token:
            return True
        # Check standard Kurdish grammatical suffix attachments
        if len(norm_token) >= 3 and w.startswith(norm_token):
            suffix = w[len(norm_token):]
            if suffix in ["", "م", "مان", "ت", "تان", "ی", "یە", "یان", "ە", "ەکە", "ەکەم", "ەکان", "ەکانم", "دا", "ش", "دا"]:
                return True
        # For 2-letter words like دل, مل, قاچ
        if len(norm_token) == 2 and w.startswith(norm_token):
            suffix = w[len(norm_token):]
            if suffix in ["م", "مان", "ت", "تان", "ی", "یە", "ە", "ەکە", "ەکەم", "دا"]:
                return True
    return False

